import assert from 'node:assert/strict';
import {week,estimated,suggestion,weekly,validLog} from './logic.mjs';
const row={id:'x',profile:'NANA',movement:0,mode:'Force',date:'2025-01-05',kind:'total',kg:40,reps:6};
assert.equal(week('2025-01-05'),'2024-12-30');
assert.equal(week('2025-01-06'),'2025-01-06');
assert.equal(estimated(row),48);
assert.equal(estimated({...row,reps:11}),null);
assert.equal(estimated({...row,kind:'lest'}),null);
assert.equal(estimated({...row,kind:'assistance'}),null);
assert.equal(estimated({...row,kg:0}),null);
assert.equal(validLog(row),true);
assert.equal(validLog({...row,reps:1.5}),false);
assert.equal(validLog({...row,kg:-1}),false);
assert.equal(validLog({...row,date:'2025-02-30'}),false);
assert.equal(suggestion([row,{...row,date:'2025-01-07',kg:60}],'2025-01-08').kg,40);
assert.equal(suggestion([row],'2025-01-04').kg,undefined);
assert.equal(suggestion([row],'2025-03-01').kg,undefined);
assert.deepEqual(weekly([row,{...row,kg:50},{...row,date:'2025-01-06',kg:42}]).map(w=>w.kg),[50,42]);
assert.equal(weekly([{...row,kind:'lest'}])[0].rm,null);
assert.equal(suggestion([row,{...row,date:'2025-01-04',kg:50}],'2025-01-08').kg,50);
assert.equal(week('2026-01-01'),'2025-12-29');
assert.equal(validLog({...row,rack:'Crochets 8'}),true);
assert.equal(validLog({...row,movement:1,rack:'8'}),false);
assert.equal(validLog({...row,movement:5,variant:'Développé debout'}),true);
assert.equal(validLog({...row,movement:5,variant:'Inconnu'}),false);
assert.equal(validLog({...row,variant:'Développé debout'}),false);
console.log('23 vérifications métier réussies.');
